import type { Metadata } from "next";
import Link from "next/link";
import sources from "../../../data/sources.json";
import { CONDITIONS } from "@/lib/conditions";

export const metadata: Metadata = { title: "About · Her Signs" };

// AHA pages block automated reading, so they are not in the search index and not cited.
const indexed = sources.filter((s) => !/heart\.org|goredforwomen\.org/.test(s.url));

export default function AboutPage() {
  return (
    <main className="mx-auto w-full max-w-3xl flex-1 px-4 py-10 sm:py-16">
      <Link href="/" className="text-sm text-muted hover:text-accent">
        ← All lessons
      </Link>
      <h1 className="mt-3 font-serif text-4xl">About Her Signs</h1>

      <p role="note" className="mt-6 rounded-md border border-alert/40 bg-surface px-4 py-3 text-sm">
        <strong className="text-alert">This is education, not medical advice.</strong> Her Signs cannot
        diagnose you. If you think you are having a heart attack or another emergency, call 911 now.
      </p>

      <Section title="Why it exists">
        Many conditions show up differently in women than the textbook picture, and much of that
        picture comes from research on men. Her Signs teaches the signs women actually report,
        through short cases with a teacher who talks you through them.
      </Section>

      <Section title="How a lesson is made">
        <ol className="mt-3 grid list-decimal gap-2 pl-5">
          <li>We collected pages from public health agencies and medical societies, listed below.</li>
          <li>Those pages are split into short passages and stored in a search index (Elastic).</li>
          <li>
            For each case, the teacher (Claude, an AI model) is given only the passages the search
            returns, and is told to use nothing else, cite each fact, and never diagnose.
          </li>
          <li>Any fact whose source was not in those passages is removed before you see it.</li>
          <li>The teacher&apos;s voice is generated by Cartesia.</li>
        </ol>
      </Section>

      <Section title="Limits">
        The cases are written by AI and can contain mistakes, so every fact links to its source for
        you to check. The people in the cases are made up. Lessons cover common warning signs, not
        every way a condition can appear. Talk to a clinician about your own health.
      </Section>

      <Section title="Privacy">
        You don&apos;t sign in and we don&apos;t ask for your name. Your browser keeps a random ID so your
        before and after quiz scores can be paired, and only those scores are stored, for the{" "}
        <Link href="/impact" className="underline">impact page</Link>.
      </Section>

      <Section title="Sources">
        {CONDITIONS.map((c) => {
          const list = indexed.filter((s) => s.condition === c.slug);
          if (!list.length) return null;
          return (
            <div key={c.slug} className="mt-4">
              <h3 className="font-semibold">{c.name}</h3>
              <ul className="mt-1.5 grid gap-1 text-sm">
                {list.map((s) => (
                  <li key={s.url}>
                    <a href={s.url} target="_blank" rel="noreferrer" className="text-accent underline underline-offset-2">
                      {s.title}
                    </a>{" "}
                    <span className="text-muted">({s.org})</span>
                  </li>
                ))}
              </ul>
            </div>
          );
        })}
      </Section>

      <Section title="Credits">
        Built solo at Cal Hacks 13.0. Teacher avatar: &ldquo;brunette&rdquo; from{" "}
        <a href="https://github.com/met4citizen/TalkingHead" className="underline">TalkingHead</a>, made with
        Ready Player Me,{" "}
        <a href="https://creativecommons.org/licenses/by-nc/4.0/" className="underline">CC BY-NC 4.0</a>.
      </Section>
    </main>
  );
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section className="mt-10">
      <h2 className="font-serif text-2xl">{title}</h2>
      <div className="mt-2 leading-relaxed">{children}</div>
    </section>
  );
}
